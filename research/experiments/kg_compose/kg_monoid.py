"""Monoid extension: non-invertible relation composition (the genuinely categorical step).

Data is generated by the full transformation monoid T3 (|T3|=27: 6 invertible = S3, 21
non-invertible). Relations are stratified into invertible (permutation) and non-invertible
(collapsing) elements. We report performance split by invertibility.

The structural point
--------------------
A non-invertible relation maps several distinct heads to the SAME tail. TransE (translation) and
RotatE (rotation) act BIJECTIVELY on the embedding space, so they *cannot* represent a collapsing
relation -- they would have to send distinct head embeddings to one point. PreNat with the MONOID
algebra uses rho(c_r) = P_{m_r}, a non-invertible 0/1 matrix that collapses by construction, and
RESCAL's free matrices can be singular too. So on the NON-INVERTIBLE columns, TransE/RotatE should
fail while PreNat(monoid)/RESCAL succeed -- and PreNat should again be far cheaper than RESCAL.

Run:  python kg_monoid.py
"""

from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "eta_sweep"))

import numpy as np
import torch

from groups import GROUPS
from kg_data import make_kg
from kg_models import build
from kg_run import train, metrics, n_params

MODELS = ["TransE", "RotatE", "RESCAL", "PreNat"]


def choose_relations(seed, n_units, n_nonunits):
    """A stratified relation set: some invertible (S3) + some non-invertible elements of T3."""
    G = GROUPS["T3"]()
    rng = np.random.default_rng(1000 + seed)
    units = [m for m in range(G.n) if G.is_unit[m] and m != G.e]
    nonunits = [m for m in range(G.n) if not G.is_unit[m]]
    rel = (list(rng.choice(units, n_units, replace=False))
           + list(rng.choice(nonunits, n_nonunits, replace=False)))
    return np.array(rel)


def mrr_subset(model, triples, mask, path=False):
    sel = triples[mask]
    if len(sel) == 0:
        return float("nan")
    if path:
        return metrics(model, sel[:, 0], [sel[:, 1], sel[:, 2]], sel[:, 3])[1]   # H@1
    return metrics(model, sel[:, 0], [sel[:, 1]], sel[:, 2])[0]                   # MRR


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=3)
    ap.add_argument("--steps", type=int, default=2500)
    ap.add_argument("--lr", type=float, default=0.02)
    ap.add_argument("--n_units", type=int, default=4)
    ap.add_argument("--n_nonunits", type=int, default=4)
    args = ap.parse_args()

    keys = ("atom_inv", "atom_noninv", "path_inv", "path_noninv", "params")
    agg = {m: {k: [] for k in keys} for m in MODELS}
    for seed in range(args.seeds):
        rel = choose_relations(seed, args.n_units, args.n_nonunits)
        data = make_kg("T3", train_frac=1.0, seed=seed, rel_elems=rel)
        ta = data["test_atomic"]
        ta_u = torch.tensor(data["test_atomic_units"])
        pq = data["pquery"]
        comp_u = torch.tensor(data["pquery_comp_units"])
        for name in MODELS:
            torch.manual_seed(seed)
            model = build(name, data)
            train(model, data, args.steps, args.lr)
            agg[name]["atom_inv"].append(mrr_subset(model, ta, ta_u))
            agg[name]["atom_noninv"].append(mrr_subset(model, ta, ~ta_u))
            agg[name]["path_inv"].append(mrr_subset(model, pq, comp_u, path=True))
            agg[name]["path_noninv"].append(mrr_subset(model, pq, ~comp_u, path=True))
            agg[name]["params"].append(n_params(model))

    G = GROUPS["T3"]()
    print(f"Monoid T3  |  entities={G.n} (units={int(G.is_unit.sum())}, "
          f"non-invertible={G.n - int(G.is_unit.sum())})  relations={args.n_units} invertible + "
          f"{args.n_nonunits} non-invertible  seeds={args.seeds}")
    print("(atomic MRR / path H@1, split by relation/composite invertibility; higher better)\n")
    hdr = (f"  {'model':8s} | {'atomic INV':^11s} | {'atomic NON-INV':^14s} | "
           f"{'path INV':^11s} | {'path NON-INV':^13s} | params")
    print(hdr)
    print("  " + "-" * (len(hdr) - 2))

    def ms(name, k):
        a = np.array(agg[name][k], dtype=float)
        return np.nanmean(a), np.nanstd(a)

    for name in MODELS:
        ai, ais = ms(name, "atom_inv"); an, ans_ = ms(name, "atom_noninv")
        pi, _ = ms(name, "path_inv"); pn, pns = ms(name, "path_noninv")
        pr = int(ms(name, "params")[0])
        print(f"  {name:8s} | {ai:5.3f}+/-{ais:4.3f} | {an:5.3f}+/-{ans_:4.3f}  | "
              f"{pi:5.3f}      | {pn:5.3f}+/-{pns:4.3f} | {pr}")

    print("\nKey column = path NON-INV H@1 (composing through a collapsing relation). TransE/RotatE "
          "act bijectively and should FAIL it; PreNat(monoid)/RESCAL should succeed; PreNat far "
          "cheaper. This is the non-invertible composition that group/rotation models cannot express.")


if __name__ == "__main__":
    main()
