"""Discovery across the group/monoid boundary: does selection find it needs NON-INVERTIBILITY?

Data is generated by the T3 monoid with a stratified relation set (invertible + non-invertible).
Candidate algebras = all four order-27 algebras we have: three abelian GROUPS (C27, C9xC3, C3x3x3,
all invertible) and the T3 MONOID (non-invertible). We do not tell the model which; we select by
validation path-query MRR.

Success = the monoid T3 is selected, because the groups -- whose regular reps are all permutation
matrices -- cannot represent the collapsing (non-invertible) relations. This is "discover that the
domain needs a non-invertible algebra", the categorical generalisation of Run 4.

Run:  python kg_monoid_select.py
"""

from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "eta_sweep"))

import numpy as np
import torch

from groups import GROUPS, ORDER27
from kg_data import make_kg
from kg_models import build
from kg_run import train, metrics
from kg_monoid import choose_relations


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=3)
    ap.add_argument("--steps", type=int, default=2500)
    ap.add_argument("--lr", type=float, default=0.02)
    args = ap.parse_args()

    cands = ORDER27
    val_mrr = {c: [] for c in cands}
    test_noninv = {c: [] for c in cands}
    selected = []
    for seed in range(args.seeds):
        rel = choose_relations(seed, 4, 4)                       # stratified T3 relations
        data = make_kg("T3", train_frac=1.0, seed=seed, rel_elems=rel)
        pq = data["pquery"]
        nval = len(pq) // 2
        val, test = pq[:nval], pq[nval:]
        comp_u_test = torch.tensor(data["pquery_comp_units"])[nval:]
        ninv = ~comp_u_test
        per = {}
        for c in cands:
            Gc = GROUPS[c]()
            algebra = {"P": torch.tensor(Gc.regular_rep()), "Tc": torch.tensor(Gc.struct_const())}
            torch.manual_seed(seed)
            model = build("PreNat", data, algebra=algebra)
            train(model, data, args.steps, args.lr)
            vm = metrics(model, val[:, 0], [val[:, 1], val[:, 2]], val[:, 3])[0]
            per[c] = vm
            val_mrr[c].append(vm)
            tn = (metrics(model, test[ninv][:, 0], [test[ninv][:, 1], test[ninv][:, 2]],
                          test[ninv][:, 3])[1] if ninv.any() else float("nan"))
            test_noninv[c].append(tn)
        selected.append(max(per, key=per.get))

    n_correct = sum(s == "T3" for s in selected)
    print("Monoid discovery  |  data = T3 monoid (non-invertible), hidden from the model")
    print(f"Candidates = 3 abelian groups + the T3 monoid (all order 27).  seeds={args.seeds}\n")
    print(f"  {'candidate':10s} {'kind':16s} | {'val path MRR':^14s} | {'test NON-INV H@1':^16s}")
    print("  " + "-" * 60)
    for c in cands:
        Gc = GROUPS[c]()
        kind = "MONOID (non-inv)" if c == "T3" else "group (invertible)"
        star = " *TRUE*" if c == "T3" else ""
        vm, vs = np.mean(val_mrr[c]), np.std(val_mrr[c])
        print(f"  {c:10s} {kind:16s} | {vm:6.3f}+/-{vs:4.3f}  | {np.nanmean(test_noninv[c]):16.3f}{star}")
    print(f"\n  Selected by validation: {selected}  ->  correct {n_correct}/{args.seeds}")
    if n_correct == args.seeds:
        print("  SUCCESS: selection discovers the domain needs a NON-INVERTIBLE (monoid) algebra; "
              "the invertible groups cannot represent the collapsing relations.")


if __name__ == "__main__":
    main()
